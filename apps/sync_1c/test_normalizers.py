"""Тесты разбора чисел из 1С (`to_decimal`).

1С 7.7 шлёт деньги/остатки строкой в разном формате. Правило (см. #271):
* пробел — всегда разделитель тысяч;
* два разных разделителя (`,` и `.`) — последний отделяет дробь, другой — тысячи;
* одиночный разделитель + ровно 3 цифры после — тысячи (НО ведущий 0 в целой
  части ⇒ дробь: «0,500» = 0.5);
* одиночный разделитель + не 3 цифры — дробь;
* повтор одного разделителя — тысячи.
"""

from decimal import Decimal

import pytest

from apps.sync_1c.normalizers import to_decimal


@pytest.mark.parametrize(
    "raw,expected",
    [
        # --- набор из задачи #271 ---
        ("1 234,50", Decimal("1234.50")),  # пробел-тысячи + запятая-дробь
        ("1.234,50", Decimal("1234.50")),  # точка-тысячи + запятая-дробь
        ("1,234", Decimal("1234")),  # одиночная запятая + 3 цифры ⇒ тысячи
        ("1234.50", Decimal("1234.50")),  # точка-дробь
        ("1234,50", Decimal("1234.50")),  # запятая-дробь
        # --- два разных разделителя: последний = дробь ---
        ("1,234.50", Decimal("1234.50")),  # запятая-тысячи + точка-дробь
        ("1 234 567,89", Decimal("1234567.89")),  # пробелы-тысячи + запятая-дробь
        # --- одиночный разделитель + 3 цифры ⇒ тысячи ---
        ("1.234", Decimal("1234")),
        ("10,500", Decimal("10500")),
        # --- ведущий 0 в целой части ⇒ дробь (решение по #271) ---
        ("0,500", Decimal("0.500")),
        ("0.500", Decimal("0.500")),
        # --- одиночный разделитель + не 3 цифры ⇒ дробь ---
        ("1,5", Decimal("1.5")),
        ("12,34", Decimal("12.34")),
        ("12,3456", Decimal("12.3456")),
        # --- повтор одного разделителя ⇒ тысячи ---
        ("1,234,567", Decimal("1234567")),
        ("1.234.567", Decimal("1234567")),
        # --- без разделителей ---
        ("1234567", Decimal("1234567")),
        ("0", Decimal("0")),
        # --- числовые типы на входе ---
        (1234.5, Decimal("1234.5")),
        (Decimal("12.34"), Decimal("12.34")),
        (1000, Decimal("1000")),
        # --- пусто / мусор ⇒ None ---
        ("", None),
        (None, None),
        ("abc", None),
        ("   ", None),
    ],
)
def test_to_decimal(raw, expected):
    result = to_decimal(raw)
    if expected is None:
        assert result is None
    else:
        assert result == expected
