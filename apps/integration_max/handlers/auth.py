"""Ответы бота вне потока одноразовой попытки.

Вход, привязка и подтверждение идут только через диплинк с сайта
(``auth_flow.py``, #492): попытку создаёт браузер, бот её завершает. Всё, что
приходит боту без живой попытки — «Старт» без ссылки, номер телефона «в
никуда», произвольный текст, — получает объяснение, что делать, и больше ничего.

Раньше здесь жил старый поток привязки по коду (#514, deprecated): бот по
номеру из контакта находил аккаунт, показывал код и сам же принимал его обратно
в чате, после чего писал ``User.max_chat_id`` и ``phone_verified=True``. Проверки,
что номер в аккаунте настоящий, не было: чужой номер, вписанный в профиль,
«подтверждался» первым же владельцем номера, открывшим бота, — и аккаунт получал
его гостевые заказы (DRF-2735). Поток удалён целиком: вводить его код на сайте
было негде, а следов использования в логах нет. ``User.max_chat_id`` остаётся
только на чтение (``services.resolve_active_chat_id``) — для тех, кто привязался
этим потоком раньше.
"""

from __future__ import annotations

# Ответ на «Старт» без ссылки и на любой текст, который бот не понимает. Раньше
# бот молчал — человек после «Вход подтверждён» писал «старт» и думал, что бот
# сломался. Живого консультанта за ботом нет, поэтому обещать ответ нельзя —
# только объяснить, зачем бот.
HELP_TEXT = (
    "Это бот магазина «Профессионал». Сюда приходят уведомления о заказах "
    "и о поступлении товара.\n\n"
    "Чтобы войти на сайт, нажмите «Войти через MAX» на странице входа — "
    "бот откроется сам и подтвердит вход. Писать сюда ничего не нужно: "
    "сообщения бот не читает."
)

# Номер прислали, а попытки, к которой он относится, нет: ссылка истекла, уже
# использована или человек нажал кнопку под старым сообщением.
STALE_LINK_TEXT = (
    "Эта ссылка уже не действует — номер никуда не передан. "
    "Вернитесь на сайт и нажмите ту же кнопку ещё раз: «Войти через MAX», "
    "«Подключить MAX» или «Отслеживать заказ в MAX»."
)


def handle_bot_started(chat_id: int, user_info: dict) -> dict:
    """«Старт» без диплинка с сайта: номер не просим, объясняем, как войти."""
    return {"chat_id": chat_id, "text": HELP_TEXT}


def handle_contact(chat_id: int, contact_payload: dict) -> dict:
    """Контакт без живой попытки. По номеру никого не ищем и ничего не пишем."""
    return {"chat_id": chat_id, "text": STALE_LINK_TEXT}


def handle_unknown_text(chat_id: int) -> dict:
    return {"chat_id": chat_id, "text": HELP_TEXT}
