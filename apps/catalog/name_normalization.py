_GENDER_INDEX = {"m": 0, "f": 1, "n": 2}

# Слова-«обёртки»: за ними идёт не признак самого товара, а зависимое
# существительное в родительном падеже. «Набор комб. ключей» — комбинированные
# здесь ключи, а не набор, поэтому род брать с первого слова нельзя. Такие
# названия оставляем как есть.
CONTAINER_WORDS = frozenset({"набор", "комплект", "ремонт", "пара", "упаковка"})

# Сокращённые названия самого типа товара — раскрываем до поиска рода, иначе
# «Перф.» и «Шлифмаш» не совпадут ни с одним ключом GENDER.
TYPE_ABBREVIATIONS: list[tuple[re.Pattern[str], str]] = [
    (re.compile(r"^\s*перф\.", re.IGNORECASE), "Перфоратор"),
    (re.compile(r"^\s*шлифмаш\.?(?=\s)", re.IGNORECASE), "Шлифмашина"),
    # «Шуруп.» с точкой — всегда шуруповёрт (349 позиций); метиз пишется без
    # точки («Шуруп 3,9х19 оцинк»), поэтому под правило не попадает.
    (re.compile(r"^\s*шуруп(ов)?\.", re.IGNORECASE), "Шуруповёрт"),
    # Здесь сокращение стоит перед типом, а не после: общий механизм согласования
    # на такой порядок не рассчитан, разбираем отдельным правилом.
    (re.compile(r"^\s*свар\.\s*(?=аппарат)", re.IGNORECASE), "Сварочный "),
]

# Единицы измерения пишутся без точки: «140мм.» → «140 мм». Список закрытый —
# «гр.» намеренно не входит: в каталоге это и граммы («453гр.»), и градусы
# («Адаптер 90гр.»), различить их регуляркой нельзя.
# Единице обязан предшествовать пробел или цифра: иначе «Клемм.» превратилось бы
# в «Кле мм» — «мм» нашлось бы внутри слова.
_UNIT_DOT = re.compile(r"(?<=[\d\s])\s*(мм|см|кг|мл)\.(?=\s|$|[,;)])", re.IGNORECASE)

# Слипшаяся точка между словами: «Головка шлиф.алмаз.D95» → «… шлиф. алмаз. D95».
_STUCK_DOT = re.compile(r"(?<=[а-яё])\.(?=[А-ЯЁA-Za-zа-я])")

_SPACE_BEFORE_PUNCT = re.compile(r"\s+([,;])")
_MULTISPACE = re.compile(r"[ \t]{2,}")

# «без аккум. и ЗУ» — здесь родительный падеж существительного, а не
# прилагательное: раскрывается отдельным правилом до общего механизма.
_NO_BATTERY = re.compile(r"\bбез\s+аккум\.", re.IGNORECASE)

_WORD = re.compile(r"^([А-Яа-яЁё]+)\.")

# Те же сокращения, но записанные в 1С без точки. Множество закрытое: без точки
# «мет» или «руч» слишком легко совпадают с началом обычного слова, поэтому
# раскрываем только проверенные по данным случаи («Шлифмаш вибр Bosch»).
DOTLESS_ABBREVIATIONS = frozenset({"вибр", "угл", "аккум", "эксц", "полир"})
_BARE_WORD = re.compile(r"^([А-Яа-яЁё]+)$")


def tidy(name: str) -> str:
    """Косметика без смены смысла: пробелы, слипшиеся точки, точки у единиц.

    Применяется и к полному названию, и к короткому — карточке нужен тот же
    аккуратный текст, только без раскрытия сокращений.
    """
    result = _STUCK_DOT.sub(". ", name)
    result = _UNIT_DOT.sub(r" \1", result)
    result = _SPACE_BEFORE_PUNCT.sub(r"\1", result)
    result = _MULTISPACE.sub(" ", result)
    return result.strip(" \t.,;")


def normalize_name(name: str) -> str:
    """Полное витринное название: сокращения раскрыты, пробелы приведены в порядок."""
    if not name:
        return name

    result = _NO_BATTERY.sub("без аккумулятора", name)
    for pattern, replacement in TYPE_ABBREVIATIONS:
        result = pattern.sub(replacement, result, count=1)
    result = tidy(result)

    words = result.split(" ")
    if not words:
        return result

    head = words[0].strip(",;").lower()
    if head in CONTAINER_WORDS:
        return result
    gender = GENDER.get(head)
    if gender is None:
        return result

    # Разворачиваем только те сокращения, что идут за типом подряд: дальше в
    # названии прилагательное относится уже к другому существительному.
    index = _GENDER_INDEX[gender]
    for position in range(1, len(words)):
        word = words[position]
        match = _WORD.match(word)
        if match is None:
            bare = _BARE_WORD.match(word)
            if bare is None or bare.group(1).lower() not in DOTLESS_ABBREVIATIONS:
                break
            match = bare
        forms = ABBREVIATIONS.get(match.group(1).lower())
        if forms is None:
            break
        words[position] = forms[index] + word[match.end() :]

    return " ".join(words)


def card_name(name: str) -> str:
    """Короткое название для карточки: как в 1С, но с прибранными пробелами.

    В плитке каталога места на «Круг алмазный отрезной 115х1,0х10х22,23 Turbo
    SUPREME Сухой рез» нет — там работает исходная телеграфная запись. Полное
    название живёт на странице товара, в заголовке вкладки и в поиске.
    """
    return tidy(name)
