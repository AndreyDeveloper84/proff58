# «д/триммера» = «для триммера». Слэш в каталоге чаще МАРКИРОВКА, а не «для»:
# «ц/х» (цилиндрический хвостовик, 830 позиций), «м/р», «а/ч», «об/мин», «л/мин»,
# «г/п», «х/б» — их трогать нельзя. Поэтому раскрываем единственную ветку «д/»,
# и только когда слева граница слова: без этого «ход/мин» превратилось бы в
# «хо для мин» (в каталоге 32 таких позиции).
_FOR_SLASH = re.compile(r"(?<![А-Яа-яЁё])д/(?=[А-Яа-яЁё])", re.IGNORECASE)

# После «д/» слово почти всегда уже стоит в родительном падеже («д/лобзика»,
# «д/мусора», «д/бурения») — там достаточно раскрыть сам предлог. Досклоняем
# только пересчитанные по каталогу исключения, где 1С обрубила окончание.
_FOR_SLASH_STEMS: dict[str, str] = {
    "триммер": "триммера",
    "бензотриммер": "бензотриммера",
    "пист": "пистолета",
    "мет": "металла",
    "пневмоинстр": "пневмоинструмента",
}
_FOR_WORD = re.compile(r"(?<=\bдля )([А-Яа-яЁё]+)\.?")

# Разделитель размера: «10x210мм» латинской «x» против «100х610» кириллической.
# Для Postgres это разные символы, и меньшинство (462 позиции против 9 663)
# обречено никогда не находиться. Приводим к кириллической — она доминирует.
_SIZE_X_LAT = re.compile(r"(?<=[0-9])[xX](?=[0-9])")

# Кириллица внутри латинской маркировки: «RВ18DLL», «CrМоV» — буквы-двойники,
# набранные не в том алфавите. Правило одностороннее: чиним только слово, где
# латиницы больше, чем кириллицы. Обратное направление («АвтоDело», «ЗУБР») не
# трогаем — там кириллица родная.
# «х» и «Х» в таблицу НЕ входят: в каталоге это прежде всего разделитель
# размера («PH3х 50 мм», «19хLED»), и перевод в латиницу спорил бы с правилом
# выше, которое как раз сводит разделитель к кириллице.
_CYR_TO_LAT = str.maketrans("АВЕКМНОРСТасеору", "ABEKMHOPCTaceopy")
_MIXED_WORD = re.compile(r"[A-Za-z0-9][A-Za-zА-Яа-яЁё0-9\-]*[А-Яа-яЁё][A-Za-zА-Яа-яЁё0-9\-]*")


def _expand_for_slash(name: str) -> str:
    """«Леска д/триммер. 2,4мм» → «Леска для триммера 2,4мм»."""
    if "д/" not in name.lower():
        return name
    result = _FOR_SLASH.sub("для ", name)

    def fix(match: re.Match[str]) -> str:
        return _FOR_SLASH_STEMS.get(match.group(1).lower(), match.group(0))

    return _FOR_WORD.sub(fix, result)


def _fix_alphabet(name: str) -> str:
    """Единый алфавит: разделитель размера и кириллица внутри латинской маркировки."""
    result = _SIZE_X_LAT.sub("х", name)

    def fix(match: re.Match[str]) -> str:
        word = match.group(0)
        lat = sum(1 for ch in word if "a" <= ch.lower() <= "z")
        cyr = sum(1 for ch in word if ch.lower() in "абвгдеёжзийклмнопрстуфхцчшщъыьэюя")
        # Кириллицы больше половины букв — слово русское, а не сбитая маркировка.
        if cyr >= lat:
            return word
        return word.translate(_CYR_TO_LAT)

    return _MIXED_WORD.sub(fix, result)


# Минимум слов, которые должны остаться в названии после снятия артикула.
# Каталог запчастей держится на артикуле: «Пружина 322890», «Демпфер 6685183»,
# «Зубчатое колесо редуктора 991887» — сняв хвост, мы получили 32 одинаковых
# «Зубчатое колесо редуктора» и 28 «Уплотнительное кольцо», неразличимых для
# покупателя. Поэтому короткие названия хвост сохраняют.
_MIN_WORDS_AFTER_ARTICLE_DROP = 4


def _drop_article_tail(name: str, article: str | None) -> str:
    """Снять артикул, продублированный в хвосте названия.

    Правило намеренно узкое, и вот почему:

    * снимаем только точное совпадение с ``article`` — коды производителя
      («…13-104 HITACHI 990021») остаются, по ним ищут в B2B;
    * артикул с пробелом не трогаем вовсе: в каталоге это не код, а типоразмер
      («Фитинг цанга прямой 6512 4-1/8», «Компрессорное масло DICREA 46 (20л)»),
      и без него позиции сливаются в одну;
    * оставляем хвост, если без него в названии меньше
      ``_MIN_WORDS_AFTER_ARTICLE_DROP`` слов — у запчастей артикул единственное,
      что их различает.
    """
    if not article:
        return name
    tail = article.strip().rstrip("*").strip()
    if not tail or len(tail) < 4:
        return name
    # Артикул с пробелом — это типоразмер, а не код.
    if any(ch.isspace() for ch in tail):
        return name
    stripped = name.rstrip(" \t,;")
    if not stripped.lower().endswith(tail.lower()):
        return name
    head = stripped[: -len(tail)].rstrip(" \t,;(-")
    # Название не должно схлопнуться в пустоту, в один артикул или в общее слово,
    # под которым в каталоге лежат десятки разных запчастей.
    if len(head) < 3 or len(head.split()) < _MIN_WORDS_AFTER_ARTICLE_DROP:
        return name
    return head


