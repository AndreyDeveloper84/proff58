# сортировки. На витрине он мусор («яяДомкрат 12 т»). В `name` его когда-то
# вычистили руками, но в `original_name` он остался у 4 547 позиций — а короткая
# форма считается именно от исходника, и без этого правила префикс вернулся бы
# на плитку каталога.
_SERVICE_PREFIX = re.compile(r"^\s*яя+(?=[А-ЯЁA-Za-z0-9])", re.IGNORECASE)


def tidy(name: str) -> str:
    """Косметика без смены смысла: пробелы, слипшиеся точки, точки у единиц.

    Применяется и к полному названию, и к короткому — карточке нужен тот же
    аккуратный текст, только без раскрытия сокращений.
    """
    result = _SERVICE_PREFIX.sub("", name)
    result = _fix_alphabet(result)
    result = _STUCK_DOT.sub(". ", result)
    result = _UNIT_DOT.sub(r" \1", result)
    result = _SPACE_BEFORE_PUNCT.sub(r"\1", result)
    result = _MULTISPACE.sub(" ", result)
    return result.strip(" \t.,;")


def normalize_name(name: str, *, article: str | None = None) -> str:
    """Полное витринное название: сокращения раскрыты, пробелы приведены в порядок.

    ``article`` нужен единственному правилу — снятию артикула, продублированного
    в хвосте названия. Без него правило просто не срабатывает.
    """
    if not name:
        return name

    result = _drop_article_tail(name, article)
    result = _expand_for_slash(result)
    result = _NO_BATTERY.sub("без аккумулятора", result)
    # Расщепляем слипшуюся точку до раскрытия типа: в «Перф.ЗУБР» тип и бренд
    # стоят без пробела, и подстановка дала бы «ПерфораторЗУБР».
    result = tidy(result)
    for pattern, replacement in TYPE_ABBREVIATIONS:
        result = pattern.sub(replacement, result, count=1)
    result = tidy(result)

    words = result.split(" ")
    if not words:
        return result

    head = words[0].strip(",;").lower()
    if head in CONTAINER_WORDS:
        return result
    gender = GENDER.get(head)
    if gender is None:
        return result

    # Разворачиваем только те сокращения, что идут за типом подряд: дальше в
    # названии прилагательное относится уже к другому существительному.
    index = _GENDER_INDEX[gender]
    for position in range(1, len(words)):
        word = words[position]
        match = _WORD.match(word)
        if match is None:
            bare = _BARE_WORD.match(word)
            if bare is None or bare.group(1).lower() not in DOTLESS_ABBREVIATIONS:
                break
            match = bare
        forms = ABBREVIATIONS.get(match.group(1).lower())
        if forms is None:
            break
        words[position] = forms[index] + word[match.end() :]

    return " ".join(words)


def card_name(name: str, *, article: str | None = None) -> str:
    """Короткое название для карточки: как в 1С, но с прибранными пробелами.

    В плитке каталога места на «Круг алмазный отрезной 115х1,0х10х22,23 Turbo
    SUPREME Сухой рез» нет — там работает исходная телеграфная запись. Полное
    название живёт на странице товара, в заголовке вкладки и в поиске.
    """
    return tidy(_drop_article_tail(name, article))
