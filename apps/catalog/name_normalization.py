"""Нормализация витринных названий товаров: «Перф. Bosch» → «Перфоратор Bosch».

Названия приходят из 1С в телеграфном стиле — «Круг алмаз. отрез. 115х1,0»,
«Винтоверт аккум. ЗУБР», «Головка шлиф.алмаз.D95». Читать это в карточке товара
тяжело, а поиск по «перфоратор» не находит позиции, названные «Перф.».

Витринное имя — контент сайта: импорт из 1С его не перезаписывает (кладёт
исходник в ``original_name``, см. apps/sync_1c/product_writer.py), поэтому
разворачивать сокращения безопасно.

**Почему не словарь «сокращение → слово».** Русское прилагательное согласуется
с существительным: «Дрель удар.» → ударн*ая*, но «Гайковерт удар.» → ударн*ый*.
Слепая замена испортила бы половину каталога. Поэтому раскрытие работает так:

1. в начале названия ищем тип товара из ``GENDER`` — он задаёт род;
2. разворачиваем идущие за ним подряд сокращения, согласуя окончание.

Цепочка обрывается на первом незнакомом слове: «Дрель удар. Makita с алмаз.
коронкой» → «Дрель ударная Makita с алмаз. коронкой». Второе сокращение
относится уже к «коронке», рода которой мы в этой позиции не знаем, и трогать
его не станем. Недоделать здесь дешевле, чем сгенерировать «с алмазный
коронкой».
"""

