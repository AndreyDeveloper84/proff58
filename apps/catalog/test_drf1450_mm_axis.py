"""DRF-1450: ось размера в миллиметрах из собственных названий 1С.

«N мм» в названии — это НЕ всегда диаметр: у шпателя это ширина полотна, у
изоленты — ширина ленты, у чашки — диаметр. Поэтому ось выбирается **по типу
инструмента**, а не по единице измерения, и три блока правил пишут в три разные
уже живые оси:

* ``str-shpateli``  → ``width``          (ширина полотна);
* ``chashki-shlif`` → ``disc_diameter``  (та же ось, что у кругов);
* ``hoz-izolenta``  → ``tape_width``     (ширина ленты).

Ось ``diameter`` (3 412 значений на стенде) не участвует ни в одном из трёх
блоков — это проверяется отдельным кейсом.

Корпус ``NAMES`` — реальные названия товаров стенда (замер 2026-09-03, выборка
«активен + в наличии»): 56 шпателей, 33 чашки, 19 изолент. Тест на своей
фикстуре, а не на синтетике: правило, зелёное на придуманных строках, ничего не
доказывает про 1С-названия, где значимы двойные пробелы, «//Remocolor»,
сокращения с точкой и пары размеров.

Проверяемые границы (каждая уже стоила проекту переделки):

1. пара «AxB» не разбирается как одно число — у зубчатого шпателя «150мм зуб
   6х6мм» ширина 150, а не 6; у чашки «125х32» диаметр 125, а посадка 32 в ось
   диаметра не попадает;
2. ``skip_if`` матчит по границе слова: «Набор шпателей» глушится, слово,
   лишь содержащее «комплект» внутри, — нет;
3. каждая ось даёт ≥2 различных значения в своём листе (правило DRF-1428),
   иначе фасет бессмысленен.
"""

