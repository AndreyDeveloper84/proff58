@pytest.fixture(scope="module")
def rules() -> AttributeRules:
    """Боевой ruleset, а не собранный в тесте: проверяем то, что уедет на стенд."""
    return AttributeRules.from_file(f"{data_dir()}/attribute_rules.json")


def extract(rules: AttributeRules, tool_type: str, name: str) -> dict[str, Decimal]:
    return {v.slug: v.number for v in rules.extract(tool_type, name)}


