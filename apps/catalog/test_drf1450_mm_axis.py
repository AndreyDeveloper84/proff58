@pytest.fixture(scope="module")
def rules() -> AttributeRules:
    """Боевой ruleset, а не собранный в тесте: проверяем то, что уедет на стенд."""
    return AttributeRules.from_file(f"{data_dir()}/attribute_rules.json")


def extract(rules: AttributeRules, tool_type: str, name: str) -> dict[str, Decimal]:
    return {v.slug: v.number for v in rules.extract(tool_type, name)}


# --------------------------------------------------------------------------- #
# 1. Ось выбрана по типу инструмента
# --------------------------------------------------------------------------- #


@pytest.mark.parametrize(
    ("tool_type", "name", "expected"),
    [
        ("str-shpateli", "Шпатель 150 мм  нерж СИБИН", Decimal("150")),
        ("str-shpateli", "Шпатель  32 мм  нерж KRAFTOOL с двухкомп.рук.", Decimal("32")),
        ("chashki-shlif", "Чашка алмазная 230 мм Турбо СЕБ", Decimal("230")),
        ("hoz-izolenta", "Изолента ПВХ 19мм х 20м белая ЗУБР Электрик-20", Decimal("19")),
    ],
)
def test_axis_is_chosen_per_tool_type(rules, tool_type, name, expected):
    assert extract(rules, tool_type, name) == {AXIS[tool_type]: expected}


def test_millimeters_never_land_in_diameter(rules):
    """Общее «мм → diameter» испортило бы живую ось с 3 412 значениями."""
    for tool_type, names in NAMES.items():
        for name in names:
            assert "diameter" not in extract(rules, tool_type, name), name


def test_only_the_declared_axis_is_written(rules):
    """Блок пишет ровно одну ось — свою; чужих осей блок не трогает."""
    for tool_type, names in NAMES.items():
        for name in names:
            assert set(extract(rules, tool_type, name)) <= {AXIS[tool_type]}, name


# --------------------------------------------------------------------------- #
# 2. Пары размеров не разбираются как одно число
# --------------------------------------------------------------------------- #


def test_notched_spatula_takes_blade_width_not_notch(rules):
    """«150мм зуб 6х6мм»: ширина полотна 150; 6 — размер зуба (ось notch_size)."""
    assert extract(
        rules, "str-shpateli", 'Шпатель 150мм зуб  6х6мм нержавеющее полотно ЗУБР "МАСТЕР"'
    ) == {"width": Decimal("150")}


def test_notch_second_member_of_pair_is_never_taken(rules):
    """Число ПОСЛЕ «х» не берётся ни при каком порядке размеров в названии."""
    assert extract(rules, "str-shpateli", "Шпатель зуб 10х10мм") == {}


def test_cup_pair_takes_diameter_not_bore(rules):
    """«125х32»: 125 — диаметр, 32 — посадка; посадка в ось диаметра не идёт."""
    assert extract(rules, "chashki-shlif", "Чашка алмазная для заточки 125х32 чашечная") == {
        "disc_diameter": Decimal("125")
    }


def test_cup_takes_first_size_not_bore_in_millimeters(rules):
    """«175 мм посад. диам. 22 мм»: берётся первый размер, а не посадочный."""
    assert extract(
        rules, "chashki-shlif", "Чашка алмазная 175 мм посад. диам. 22 мм по бетону"
    ) == {"disc_diameter": Decimal("175")}


@pytest.mark.parametrize(
    "name",
    [
        "Чашка алмазная 125*22,2*20 Турбо  Hitachi",
        "Чашка алмазная 125х5х22 мм Двухрядная",
        "Чашка алмазная 100/22,23-15 №00 DGM-S Exstra-Activ",
    ],
)
def test_triple_size_is_left_alone(rules, name):
    """Тройка размеров одного значения не имеет — молчим, а не пишем осколок.

    Разделители значимы: «100/22,23-15» — не то же, что «100 22 23 15»;
    «нормализация для надёжности» здесь уже приводила к откату прогона.
    """
    assert extract(rules, "chashki-shlif", name) == {}


def test_tape_length_in_metres_is_not_width(rules):
    """«19мм х 20м»: 20 — длина рулона в метрах, в ось ширины не попадает."""
    assert extract(rules, "hoz-izolenta", "Изолента ПВХ 19мм х 20м белая") == {
        "tape_width": Decimal("19")
    }


