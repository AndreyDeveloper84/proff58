# 3. skip_if — по границе слова, а не по подстроке
# --------------------------------------------------------------------------- #


@pytest.mark.parametrize(
    "name",
    [
        "Набор шпателей 3 предмета:40,60,80мм STAYER MASTER",
        "Шпатель  50,80,100,120мм набор 4шт (япончик)",
    ],
)
def test_sets_have_no_single_width(rules, name):
    assert extract(rules, "str-shpateli", name) == {}


def test_skip_if_does_not_swallow_word_containing_stopword(rules):
    """« шт» глушило «штампованный», «комплект» — «БОЕКОМПЛЕКТ»: здесь не должно."""
    assert extract(rules, "str-shpateli", "Шпатель 100 мм БОЕКОМПЛЕКТ") == {"width": Decimal("100")}


def test_abbreviation_dot_does_not_block_the_size(rules):
    """«резин.180 мм»: точка сокращения — не десятичный разделитель."""
    assert extract(rules, "str-shpateli", 'Шпатель резин.180 мм, черный,STAYER"MASTER"') == {
        "width": Decimal("180")
    }


def test_decimal_tail_is_not_read_as_a_separate_size(rules):
    """«22,2 мм» — одно дробное число, «2 мм» из него не вырезается."""
    assert extract(rules, "hoz-izolenta", "Изолента 22,2 мм") == {}


# --------------------------------------------------------------------------- #
# 4. Корпус целиком: покрытие и правило «ось нужна от двух значений»
# --------------------------------------------------------------------------- #


@pytest.mark.parametrize(
    ("tool_type", "expected_hits"),
    [("str-shpateli", 53), ("chashki-shlif", 33), ("hoz-izolenta", 19)],
)
def test_corpus_coverage_is_locked(rules, tool_type, expected_hits):
    """Замер стенда 2026-09-03: 105 значений на 108 товарах в наличии."""
    hits = [n for n in NAMES[tool_type] if AXIS[tool_type] in extract(rules, tool_type, n)]
    assert len(hits) == expected_hits


def test_every_axis_has_at_least_two_distinct_values(rules):
    """Правило DRF-1428: ось с одним значением фасета не даёт — заводить нельзя."""
    for tool_type, names in NAMES.items():
        values = {extract(rules, tool_type, n).get(AXIS[tool_type]) for n in names} - {None}
        assert len(values) >= 2, (tool_type, values)
