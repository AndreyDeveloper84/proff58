def bounds(rules, tool_type, name, lo_slug, hi_slug):
    got = extract(rules, tool_type, name)
    return got.get(lo_slug), got.get(hi_slug)


@pytest.mark.parametrize(
    "name",
    [
        "Струбцина пистолетная 150/60 мм HP-15/6, HERCULES-STAYER",
        "Струбцина пистолетная 450/630 мм HERCULES-P STAYER",
        "Струбцина Т-образный профиль KRAFTOOL TBC/6 1650/55мм",
    ],
)
def test_slash_pair_is_never_read_as_a_range(rules, name):
    """Пара через дробь — не диапазон, и это доказывает сама выборка.

    У «150/60» первое число больше, у «450/630» меньше: порядок непостоянен,
    а смысл у брендов разный (раскрытие/глубина против длины/ширины профиля).
    Развернуть такую пару в «от/до» значило бы местами получить «от 150 до 60».
    """
    assert bounds(rules, "strubtsiny", name, "clamp_from", "clamp_to") == (None, None)


@pytest.mark.parametrize(
    "name",
    [
        "Струбцина тип F, 50х250мм  двухкомпонентная ручка",
        "Струбцина тип F рычажная, быстрозажим. 75*200мм KR",
        'Струбцина тип "G" 82х120мм с глубокой рамкой',
    ],
)
def test_cross_pair_is_two_quantities_not_bounds(rules, name):
    """«50х250мм» — вылет на раскрытие: две РАЗНЫЕ величины, а не границы одной."""
    assert bounds(rules, "strubtsiny", name, "clamp_from", "clamp_to") == (None, None)


def test_clamp_range_and_single_share_one_axis_pair(rules):
    """Диапазон и одно число ложатся в одну пару осей и потому сравнимы."""
    assert bounds(rules, "strubtsiny", "Струбцина 0-100 мм STAYER", "clamp_from", "clamp_to") == (
        Decimal("0"),
        Decimal("100"),
    )
    assert bounds(
        rules, "strubtsiny", "Струбцина тип G 100 мм, KRAFTOOL", "clamp_from", "clamp_to"
    ) == (Decimal("100"), Decimal("100"))


def test_no_inverted_bounds_anywhere(rules):
    """«от» никогда не больше «до» — иначе фильтр по паре молча пустеет."""
    for tool_type, lo_slug, hi_slug in (
        ("strubtsiny", "clamp_from", "clamp_to"),
        ("krep-styazhki", "hose_diameter_from", "hose_diameter_to"),
        ("str-markery", "tip_width_from", "tip_width_to"),
    ):
        for name in NAMES[tool_type]:
            lo, hi = bounds(rules, tool_type, name, lo_slug, hi_slug)
            if lo is None or hi is None:
                assert lo is None and hi is None, name
                continue
            assert lo <= hi, (name, lo, hi)


