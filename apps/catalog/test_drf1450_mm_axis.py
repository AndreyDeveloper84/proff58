def test_millimeters_never_land_in_a_foreign_axis(rules):
    """Общее «мм → diameter» испортило бы живую ось с 3 412 значениями.

    Инвариант именно в том, что ось ЧУЖАЯ. У лески diameter — её собственная
    ось (толщина лески), у зубил он объявлен для кернеров и бородков, и
    запрещать его там значило бы запрещать правильный ответ. Поэтому
    пропускаем типы, которые diameter объявили, и требуем его отсутствия у
    всех остальных: именно эта ошибка однажды и стоила проекту переделки.
    """
    for tool_type, names in NAMES.items():
        if "diameter" in {AXIS[tool_type]} | EXTRA_AXES.get(tool_type, set()):
            continue
        for name in names:
            assert "diameter" not in extract(rules, tool_type, name), name


# Оси, объявленные блоком помимо размерной (см. AXIS). Список закрытый:
# любая новая ось обязана быть внесена сюда осознанно, иначе тест упадёт —
# именно так и должно быть, потому что появление оси в типе меняет витрину.
EXTRA_AXES: dict[str, set[str]] = {
    "napilniki": {"file_shape", "file_cut"},
    "str-markery": {"tip_width_to"},
    "strubtsiny": {"clamp_to"},
    "krep-styazhki": {"hose_diameter_to"},
    "krep-shurupy": {"length"},
    "zubila": {"width", "diameter"},
    "nozhi": {"length"},
}


def test_block_writes_only_the_axes_it_declares(rules):
    """Размерная ось у блока строго одна, остальные — только объявленные.

    Этот же тест закрывает и «блок не пишет в ось соседнего типа»: всё, что
    не объявлено самим блоком, для него чужое. Отдельная проверка на чужие
    оси была бы слабее — она не знала бы про EXTRA_AXES и падала бы на
    шурупах, которые законно объявляют и diameter, и length.

    Две размерных оси в одном названии неминуемо начали бы делить между собой
    одни и те же миллиметры. Форма и насечка напильников этому не мешают: они
    select и берутся из слов, а не из чисел.
    """
    for tool_type, names in NAMES.items():
        allowed = {AXIS[tool_type]} | EXTRA_AXES.get(tool_type, set())
        for name in names:
            assert set(extract(rules, tool_type, name)) <= allowed, name


