"""ДРФ-1449: ось «число зубьев» у пильных дисков.

Число зубьев — главное отличие пильного диска от отрезного круга: у круга
такой оси нет вовсе, там значимы толщина и материал обработки. Ось заводится
только после того, как пильные диски получили собственный ``tool_type``
(``pilnye-diski``, манифест 360 → 361), иначе она была бы пустой у половины
пула и заполненной у другой — ровно тот случай, из-за которого фасет прячет
выдачу вместо того, чтобы её сужать.

Корпус ``NAMES`` — реальные названия товаров листа 87 стенда (замер
2026-09-05, все 327 позиции листа). Тест на своей фикстуре, а не на синтетике:
правило, зелёное на придуманных строках, ничего не доказывает про 1С-названия,
где число зубьев записано четырьмя разными формами, а рядом стоят габариты,
толщина и бренд из заглавных букв.

Проверяемые границы (каждая найдена замером, а не придумана):

1. **Четыре формы записи** дают одно и то же число: ``z-48``/``z16``/``Z-12``
   (172 товара), ``24Т``/``100Т`` (103), ``Z70зуб`` (6), ``3 резца`` (4).
   На 26 товарах формы встречаются одновременно — числа обязаны совпасть.
2. **Толщина не должна попасть в ось.** В «160х16тх32» после «т» идёт
   кириллическая «х», и правая граница обязана это заблокировать. В
   «125х3Тх22 z-3» по той же причине побеждает z-форма.
3. **``skip_if`` не ставится.** Он матчит подстроку, а в листе есть бренд
   «БОЕКОМПЛЕКТ» — стандартный ``skip_if: ["комплект"]`` молча съел бы два
   законных значения (z36 и z60).
4. **Ось живёт только у пильных дисков.** У ``krugi-shlif``, откуда диски
   ушли, ``teeth_count`` быть не должно.
5. Ось даёт ≥2 различных значения (правило DRF-1428), иначе фасет бессмысленен.
"""

