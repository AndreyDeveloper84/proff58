@pytest.fixture(scope="module")
def rules() -> AttributeRules:
    return AttributeRules.from_file(data_dir() / "attribute_rules.json")


def _teeth(rules: AttributeRules, name: str):
    for value in rules.extract(TOOL_TYPE, name):
        if value.slug == AXIS:
            return value.number
    return None


@pytest.mark.parametrize("name,expected", NAMES, ids=[n[:44] for n, _ in NAMES])
def test_teeth_count_extracted_from_real_names(rules, name, expected):
    got = _teeth(rules, name)
    if expected is None:
        assert got is None, f"ложное срабатывание: {got}"
    else:
        assert got == Decimal(expected)


def test_thickness_never_lands_in_teeth_axis(rules):
    """«160х16тх32»: после «т» идёт кириллическая «х» — правая граница держит."""
    assert _teeth(rules, "Диск пильный 160х16тх32 Атака") is None


def test_boekomplekt_brand_is_not_swallowed(rules):
    """skip_if матчит подстроку — «комплект» внутри бренда съел бы значение."""
    assert _teeth(rules, "Диск пильный 165х30/20 z36 БОЕКОМПЛЕКТ") == Decimal(36)
    assert _teeth(rules, "Диск пильный 255х30 z60 БОЕКОМПЛЕКТ") == Decimal(60)


def test_rule_has_no_skip_if(rules):
    """Явная фиксация решения: у оси не должно появиться skip_if."""
    rule = next(r for r in rules.rules_for(TOOL_TYPE) if r.slug == AXIS)
    assert not rule.skip_if, f"skip_if вернулся: {rule.skip_if}"


def test_axis_absent_for_circles(rules):
    """У отрезных кругов числа зубьев нет — ось не должна туда протечь."""
    assert all(r.slug != AXIS for r in rules.rules_for("krugi-shlif"))


def test_axis_yields_at_least_two_distinct_values(rules):
    """Правило DRF-1428: ось с одним значением фасетом быть не может."""
    values = {_teeth(rules, n) for n, e in NAMES if e is not None}
    assert len(values - {None}) >= 2


def test_forms_agree_when_both_present(rules):
    """Где формы встречаются вместе, число обязано быть одним."""
    assert _teeth(rules, "Диск пильный 150х20 z=36Т ЗУБР  ЧИСТОРЕЗ") == Decimal(36)
    assert _teeth(rules, "Диск пильный 355х25,4 DeWalt , Z70зуб (по металлу") == Decimal(70)


def test_comma_after_number_is_a_separator_not_a_decimal(rules):
    r"""«Z=48,» — запятая разделяет поля названия, а не начинает дробь.

    Первая редакция правила несла lookahead ``(?![\d.,])`` и теряла 9 товаров
    из 327: «Z=48, ЗУБР ПРОФИ», «Z18, толщина диска/пропила», «Z=100, …».
    Запрещать нужно ЧАСТИЧНОЕ чтение числа (цифра или дробная часть следом),
    а не любой знак после него.
    """
    assert _teeth(rules, "Диск пильный 160х20 Z=48, ЗУБР") == Decimal(48)
    assert _teeth(rules, "Диск пильный 165х30/20 Z18, толщина 1,2/1,8мм") == Decimal(18)
    # но дробь по-прежнему не читается частично
    assert _teeth(rules, "Диск пильный 200х32 z48,5 странное") is None


def test_left_boundary_blocks_partial_read_of_long_numbers(rules):
    """«1234т» не должно прочитаться как 234 — левая граница держит."""
    assert _teeth(rules, "Диск пильный 1234т непонятный") is None
    assert _teeth(rules, "Диск пильный 1234 зуба непонятный") is None
