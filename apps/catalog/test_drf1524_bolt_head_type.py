"""ДРФ-1524: два дефекта правил, найденные при прогоне уже написанного.

Замер 2026-09-09 показал, что по каталогу извлекается 8901 значение, которое не
записано в БД. При попытке прогнать самые крупные типы сверка остановила два из
них — правила писали неверные значения, и запись отложена до этих правок.

## Болты: ключ «шестигр» ловил шлиц, а не форму головки

«С внутренним шестигранником» — это **способ затяжки**, а не форма головки.
Из 200 болтов с этим словом двадцать получали «Шестигранную» неверно, причём
**восемь прямо говорили «с потайной головкой»** (DIN 7991): движок писал
значение, противоположное явному тексту названия. Остальные двенадцать — DIN
912, головка цилиндрическая.

Замер: настоящих шестигранных 180, из них 177 называют «головку», три
опознаются по DIN 933 — это и есть стандарт болта с шестигранной головкой.

**Опция «Цилиндрическая» добавлена в КОНЕЦ списка намеренно.** Порядок опций в
массиве задаёт и приоритет матчинга, и ``sort_order`` варианта в фасете; вставка
в середину переставила бы уже существующие варианты на витрине. В конце она
безопасна: «потай» проверяется раньше и забирает DIN 7991, а до цилиндрической
доходят только те, у кого не нашлось ни головки, ни потая.

## Ключи: правка ОТКАЧЕНА, нужно решение владельца

Пара «10х11» действительно читается как размер 11, и на стенде у 179 товаров
из 181 такой неверный размер уже записан. Но это **осознанное расхождение**, а
не дефект: в ``test_attribute_extract.py`` стоит якорный тест
``test_size_pair_is_kept_deliberately`` с прямым указанием — «расхождение
должно сниматься решением, а не рефакторингом». Гейт на пару был написан и
откачен: он ронял четыре якорных случая и вдобавок разводил поведение ключей и
головок, у которых пара тоже сохраняется. Ждёт решения владельца.
"""

from __future__ import annotations

import json
from decimal import Decimal

import pytest

from apps.catalog.attribute_extract import AttributeRules
from apps.catalog.ingest import data_dir

BOLT = "krep-bolty"


@pytest.fixture(scope="module")
def rules() -> AttributeRules:
    return AttributeRules.from_file(data_dir() / "attribute_rules.json")


def _val(rules: AttributeRules, tool_type: str, axis: str, name: str):
    for v in rules.extract(tool_type, name):
        if v.slug == axis:
            return v.option_slug or v.number
    return None


@pytest.mark.parametrize(
    "name,expected",
    [
        # Настоящая шестигранная ГОЛОВКА — слово «головка» в разных формах.
        ("Болт М10х100 шестигр. головка", "hex"),
        ("Болт М 10х120 шестигр. головка с неполной резьбой, кл. прочн.10,9, DIN933", "hex"),
        ("Болт М10х 10 шестигр. головка DIN933 А4", "hex"),
        ("Болт М 6х20 DIN933 шестигранная голова полная резьба", "hex"),
        # Три названия без слова «головка» опознаются по стандарту DIN 933.
        ("Болт М14х65 цинк шестигран DIN 933", "hex"),
        ("Болт М14х70 цинк шестигран DIN 933", "hex"),
        # Шлиц, а не головка: DIN 912 — цилиндрическая.
        ("Болт М5х20 с внутренним шестигранником А2 DIN 912", "cylindrical"),
        ("Болт М6х30 внутр. шестигр. А2 DIN 912", "cylindrical"),
        ("Винт М10х120 с внутр. шестигр. оксидированный, 12,9, DIN 912", "cylindrical"),
        ("Болт М24х60 оцинкованный с внутренним шестигранником, DIN912", "cylindrical"),
        # Шлиц + явная потайная головка: DIN 7991.
        ("Винт М6х20 с внутренним шестигранником и потайной головкой DIN 7991, 8.8", "countersunk"),
        ("Винт М8х30 с внутренним шестигранником и потайной головкой DIN 7991", "countersunk"),
        (
            "Винт 10х25 класса прочности 10.9 с потайной головкой и внутренним шестигранником",
            "countersunk",
        ),
    ],
)
def test_bolt_head_type(rules, name, expected):
    """Форма головки читается по головке, а не по способу затяжки."""
    assert _val(rules, BOLT, "head_type", name) == expected


def test_internal_hex_never_yields_hex_head(rules):
    """Главный дефект: «с внутренним шестигранником» — это шлиц.

    Восемь товаров из двадцати прямо говорили «с потайной головкой», то есть
    движок писал значение, противоположное явному тексту названия.
    """
    for name in (
        "Болт М5х20 с внутренним шестигранником А2 DIN 912",
        "Винт М5х60 с внутренним шестигранником А2 DIN912",
        "Винт М8х50 с внутренним шестигранником и потайной головкой из нержавейки",
        "Болт с внутр. шестигр. М 6х25 DIN912 белый цинк",
    ):
        assert _val(rules, BOLT, "head_type", name) != "hex", name


def test_cylindrical_option_is_appended_not_inserted():
    """Порядок опций задаёт и матчинг, и sort_order варианта в фасете.

    Вставка «Цилиндрической» в середину переставила бы уже существующие
    варианты на витрине; в конце она безопасна, потому что «потай»
    проверяется раньше и забирает DIN 7991.
    """
    data = json.loads((data_dir() / "attribute_rules.json").read_text(encoding="utf-8"))
    block = next(b for b in data["tool_types"] if b["tool_type"] == BOLT)
    axis = next(a for a in block["attributes"] if a["slug"] == "head_type")
    order = [o["slug"] for o in axis["options"]]
    assert order[:4] == ["hex", "countersunk", "round", "flange"], "прежний порядок сохранён"
    assert order[-1] == "cylindrical", "новая опция добавлена в конец"


def test_four_digit_bolt_length(rules):
    """Длина брала три цифры и обрезала «М30х1000» до 100."""
    name = "Болт 1.1 М30х1000 09Г2С ГОСТ 24379.1-2012 комплект"
    assert _val(rules, BOLT, "length", name) == Decimal("1000")
    assert _val(rules, BOLT, "thread_diameter", name) == Decimal("30")


def test_three_digit_lengths_still_work(rules):
    """Регресс: расширение до четырёх цифр не должно ломать обычные длины."""
    assert _val(rules, BOLT, "length", "Болт М10х100 шестигр. головка") == Decimal("100")
    assert _val(rules, BOLT, "length", "Болт М6х30 внутр. шестигр. А2 DIN 912") == Decimal("30")
