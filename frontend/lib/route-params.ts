/**
 * Значение динамического сегмента маршрута из useParams().
 *
 * Next (App Router) отдаёт сегменты в том виде, в каком они стоят в адресе, то
 * есть закодированными: номер заказа «П-20260803-CC74CA» приходит как
 * «%D0%9F-20260803-CC74CA». Наши номера начинаются с кириллической «П», поэтому
 * это касается каждого заказа, а не редкого случая:
 *
 *   • getOrder() кодировал полученное ещё раз, запрос уходил на
 *     /api/orders/%25D0%259F-… , Django искал заказ с номером «%D0%9F-…» и
 *     отвечал 404 — карточка заказа не открывалась вообще;
 *   • страница «Заказ принят» читала снимок из sessionStorage по закодированному
 *     ключу, а checkout клал его по обычному номеру, так что снимок не
 *     находился никогда, и в заголовке светился «№ %D0%9F-…».
 *
 * decodeURIComponent идемпотентен для наших значений (кириллица, цифры и дефисы,
 * знака «%» внутри нет) — повторный вызов на уже раскодированной строке ничего
 * не меняет. Оборванную последовательность («%» без пары цифр) возвращаем как
 * есть: пусть сервер ответит по фактическому значению, а страница не упадёт с
 * URIError.
 */
export function decodeRouteParam(value: string): string {
  try {
    return decodeURIComponent(value);
  } catch {
    return value;
  }
}
