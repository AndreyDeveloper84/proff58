/**
 * Параметр маршрута из useParams() — в исходном виде.
 *
 * Next (App Router) отдаёт динамические сегменты ЗАКОДИРОВАННЫМИ: для номера
 * заказа «П-20260803-CC74CA» в params прилетает «%D0%9F-20260803-CC74CA».
 * Дальше этот номер шёл в API и в ключ sessionStorage как есть, поэтому:
 *
 *   • getOrder() кодировал его повторно → запрос уходил на
 *     /api/orders/%25D0%259F-… , Django искал заказ с номером «%D0%9F-…»
 *     и отвечал 404 («Данные не найдены — возможно, страница устарела»);
 *   • /thanks читал снимок заказа по закодированному ключу, а checkout писал
 *     его по обычному номеру → снимок не находился НИКОГДА, и страница всегда
 *     показывала «Детали заказа не сохранились в этом браузере».
 *
 * decodeURIComponent идемпотентен для наших значений (номер заказа — кириллица,
 * цифры и дефисы, символа «%» в нём нет), поэтому повторный вызов на уже
 * раскодированной строке безопасен. Битую последовательность («%» без пары
 * цифр) отдаём как есть: пусть сервер ответит 404 по реальному значению, а
 * страница не падает с URIError.
 */
export function decodeRouteParam(value: string): string {
  try {
    return decodeURIComponent(value);
  } catch {
    return value;
  }
}
