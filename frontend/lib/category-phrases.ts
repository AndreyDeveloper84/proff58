// Названия разделов в родительном падеже — для фраз «Все виды электроинструмента»
// и «Популярные виды электроинструмента» (DRF-991, Блоки 2–3).
//
// Падеж по названию автоматически не вывести: русская морфология не выводится из
// строки, а тянуть ради двух фраз библиотеку склонений — несоразмерно. Поэтому
// статическая карта по образцу lib/category-artwork.ts: те же 14 корневых разделов,
// тот же принцип «незнакомое имя — не ломаемся, а деградируем к общей фразе».

// Порядок важен ровно так же, как в category-artwork: частное проверяется до общего.
// Классы символов — кириллические явно: \w в JS это [A-Za-z0-9_], на «Ручной» он не сработает.
const GENITIVE: Array<[RegExp, string]> = [
  [/электроинструмент/i, "электроинструмента"],
  [/оснастк|расходн/i, "оснастки"],
  [/ручн[а-яё]*\s+инструмент/i, "ручного инструмента"],
  [/измерительн/i, "измерительного инструмента"],
  [/строительн|отделочн/i, "строительного инструмента"],
  [/крепёж|крепеж|метиз/i, "крепежа"],
  [/электрик|освещ/i, "электрики"],
  [/садов/i, "садовой техники"],
  [/запчаст|аккумулятор/i, "запчастей"],
  [/спецодежд|сиз/i, "спецодежды"],
  [/силов[а-яё]*\s+техник|пневмо/i, "силовой техники"],
  [/хранени|организаци/i, "решений для хранения"],
  [/сварочн/i, "сварочного оборудования"],
  [/автоинструмент|гараж/i, "автоинструмента"],
];

/** Название раздела в родительном падеже либо null, если раздел незнакомый. */
export function categoryGenitive(title: string): string | null {
  const name = (title || "").trim();
  if (!name) return null;
  return GENITIVE.find(([test]) => test.test(name))?.[1] ?? null;
}

/**
 * Подпись возврата к полному списку типов: «Все виды электроинструмента».
 * Для незнакомого раздела — «Все виды»: короче, но не врёт.
 */
export function allTypesLabel(title: string): string {
  const genitive = categoryGenitive(title);
  return genitive ? `Все виды ${genitive}` : "Все виды";
}

/** Заголовок панели типов: «Популярные виды электроинструмента» (Блок 2). */
export function popularTypesTitle(title: string): string {
  const genitive = categoryGenitive(title);
  return genitive ? `Популярные виды ${genitive}` : "Популярные виды";
}
